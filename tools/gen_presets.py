#!/usr/bin/env python3
"""Compile Presets/*.json into GeneratedPresets.h.

Each preset file looks like:

    { "name": "Big Bass", "params": { "cutoff": -0.5, "fDecay": 0.25 } }

The keys are ParamSpec::symbol values from plugin/PlainOldSynthParams.h. Keys are kept as STRINGS
in the generated header and resolved by the plugin at run time (paramIndexForSymbol), so this tool
never has to know the parameter table itself and a stale key can never renumber anything — an
unknown symbol is simply ignored when the preset is applied.

Presets are emitted in sorted-filename order so the generated header is deterministic.
"""

import argparse
import json
import os
import sys


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def c_float(value) -> str:
    # %.6g gives "1" for integral values, which is not a float literal in C++ — add the ".0".
    text = f"{float(value):.6g}"
    if not any(c in text for c in ".eE"):
        text += ".0"
    return text + "f"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("files", nargs="+", help="Presets/*.json")
    ap.add_argument("-o", "--output", required=True, help="path of the GeneratedPresets.h to write")
    args = ap.parse_args()

    presets = []
    for path in sorted(args.files):
        with open(path, "r", encoding="utf-8") as handle:
            try:
                doc = json.load(handle)
            except json.JSONDecodeError as exc:
                sys.exit(f"{path}: not valid JSON: {exc}")
        name = doc.get("name")
        if not isinstance(name, str) or not name:
            sys.exit(f"{path}: needs a non-empty \"name\"")
        params = doc.get("params", {})
        if not isinstance(params, dict):
            sys.exit(f"{path}: \"params\" must be an object of symbol -> number")
        for key, value in params.items():
            if not isinstance(value, (int, float)) or isinstance(value, bool):
                sys.exit(f"{path}: value for {key!r} must be a number")
        presets.append((name, list(params.items()), os.path.basename(path)))

        # Only the last preset in a duplicate-name run survives, and that is silent otherwise.
    seen = {}
    for name, _, src in presets:
        if name in seen:
            sys.exit(f"duplicate preset name {name!r} ({seen[name]} and {src})")
        seen[name] = src

    out = []
    out.append("// Generated by tools/gen_presets.py from Presets/*.json — do not edit by hand.")
    out.append("// Regenerate by rebuilding (CMake reruns the generator when a preset file changes).")
    out.append("#pragma once")
    out.append("")
    out.append('#include "PlainOldSynthParams.h"')
    out.append("")
    out.append("namespace plainoldsynth {")
    out.append("")
    for i, (_, params, _) in enumerate(presets):
        out.append(f"inline constexpr PresetValue kPreset{i:02d}Values[] = {{")
        for key, value in params:
            out.append(f"    {{ {c_string(key)}, {c_float(value)} }},")
        if not params:
            out.append("    { nullptr, 0.0f },   // preset with no values: defaults only")
        out.append("};")
        out.append("")
    out.append("inline constexpr PresetEntry kPresets[] = {")
    for i, (name, params, _) in enumerate(presets):
        out.append(f"    {{ {c_string(name)}, {len(params)}, kPreset{i:02d}Values }},")
    out.append("};")
    out.append("")
    out.append(f"inline constexpr uint32_t kPresetCount = {len(presets)}u;")
    out.append("")
    out.append("} // namespace plainoldsynth")
    out.append("")

    text = "\n".join(out)
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    # Only touch the file when the content changed, so a rebuild doesn't churn the timestamps.
    try:
        with open(args.output, "r", encoding="utf-8") as handle:
            if handle.read() == text:
                return 0
    except OSError:
        pass
    with open(args.output, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"gen_presets: wrote {args.output} ({len(presets)} presets)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
